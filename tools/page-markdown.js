// Plain, complete lesson Markdown for explicit user copying. No browser DOM or AI service.
const fs=require('node:fs'),path=require('node:path');
const VISUAL_NOTE='> Export note: Diagrams generated by the website and interactive controls are not embedded in this Markdown. The complete authored lesson text is included.';
function widgetNote(id){return '> Interactive widget: `'+id+'` — available in the website; its controls and visual state are not included here.';}
function exportLessonMarkdown(source){
  let fence=null;
  const markdown=String(source).replace(/\r\n/g,'\n').replace(/^\uFEFF/,'').split('\n').map(line=>{
    const marker=line.match(/^ {0,3}(`{3,}|~{3,})(.*)$/);
    if(marker){
      if(!fence)fence={character:marker[1][0],length:marker[1].length};
      else if(marker[1][0]===fence.character&&marker[1].length>=fence.length&&!marker[2].trim())fence=null;
      return line;
    }
    if(fence)return line;
    const widget=line.match(/^\s*<div\b(?=[^>]*\bclass="widget")(?=[^>]*\bdata-widget="([a-z0-9-]+)")[^>]*>\s*<\/div>\s*$/i);
    return widget?widgetNote(widget[1]):line;
  }).join('\n');
  return markdown+'\n\n'+VISUAL_NOTE+'\n';
}
function buildMarkdownExports(root=path.resolve(__dirname,'..')){
  const lessons={};
  for(const [track,directory,pattern]of [['m','modules',/^(\d\d)-.*\.md$/],['s','survey',/^S(\d\d)-.*\.md$/]]){
    for(const file of fs.readdirSync(path.join(root,'course',directory)).sort()){
      const match=file.match(pattern);if(!match)continue;
      lessons['#/'+track+'/'+match[1]]=exportLessonMarkdown(fs.readFileSync(path.join(root,'course',directory,file),'utf8'));
    }
  }
  const output=path.join(root,'site/ai-content.js'),bytes='window.COURSE_MARKDOWN = Object.freeze('+JSON.stringify(lessons)+');\n';
  if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==bytes)fs.writeFileSync(output,bytes);
  return {lessons:Object.keys(lessons).length,bytes:Buffer.byteLength(bytes),output};
}
if(require.main===module)console.log(JSON.stringify(buildMarkdownExports(),null,2));
module.exports={exportLessonMarkdown,buildMarkdownExports,VISUAL_NOTE,widgetNote};
